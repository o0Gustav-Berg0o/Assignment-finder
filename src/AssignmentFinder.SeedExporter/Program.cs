using System.Globalization;
using System.Text;
using AssignmentFinder.Infrastructure.Data;
using Microsoft.AspNetCore.DataProtection.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

// Exports the admin-configured parts of the database (Brokers, SearchCriteria, and the Data
// Protection keys that decrypt Broker login passwords) as an idempotent SQL script, so that
// config built up by hand against one environment (e.g. this local/docker instance) can be
// replayed against a fresh database - typically when migrating the app to a cloud host.
//
// Deliberately excludes Assignments/Matches/AspNetUsers: scraped data is rebuilt by the next
// scan, and migrating user accounts is a separate concern (SearchCriteria.UserId must already
// exist in the target database's AspNetUsers table, or those rows will fail their FK constraint).
//
// Usage: dotnet run --project src/AssignmentFinder.SeedExporter -- "<connection-string>" [--out <path>]
//   If no connection string is given, ConnectionStrings__Default (matching the API/Worker's own
//   configuration convention) is used.

var connectionString = args.FirstOrDefault(a => !a.StartsWith("--", StringComparison.Ordinal))
    ?? Environment.GetEnvironmentVariable("ConnectionStrings__Default")
    ?? throw new InvalidOperationException(
        "Pass a connection string as the first argument, or set the ConnectionStrings__Default environment variable.");

var outputPath = GetOption(args, "--out") ?? Path.Combine("seed-data", "seed-brokers-and-searches.sql");

var options = new DbContextOptionsBuilder<AppDbContext>().UseSqlServer(connectionString).Options;
await using var db = new AppDbContext(options);

var brokers = await db.Brokers.AsNoTracking().OrderBy(b => b.Id).ToListAsync();
var searchCriteria = await db.SearchCriteria.AsNoTracking().OrderBy(s => s.Id).ToListAsync();
var dataProtectionKeys = await db.DataProtectionKeys.AsNoTracking().OrderBy(k => k.Id).ToListAsync();

var sql = new StringBuilder();
sql.AppendLine("-- Generated by AssignmentFinder.SeedExporter on " + DateTimeOffset.UtcNow.ToString("u", CultureInfo.InvariantCulture));
sql.AppendLine("-- Syncs Brokers, SearchCriteria and DataProtectionKeys from the source database this ran against.");
sql.AppendLine("-- Apply EF Core migrations to the target database FIRST, then run this script against it.");
sql.AppendLine("-- SearchCriteria rows reference AspNetUsers(Id); migrate/seed matching users first or those");
sql.AppendLine("-- MERGE statements will fail their foreign-key check.");
sql.AppendLine();

AppendBrokersMerge(sql, brokers);
AppendSearchCriteriaMerge(sql, searchCriteria);
AppendDataProtectionKeysMerge(sql, dataProtectionKeys);

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outputPath))!);
await File.WriteAllTextAsync(outputPath, sql.ToString());

Console.WriteLine(
    $"Wrote {brokers.Count} broker(s), {searchCriteria.Count} saved search(es), " +
    $"{dataProtectionKeys.Count} data-protection key(s) to {outputPath}");

return;

static string? GetOption(string[] args, string name)
{
    var index = Array.IndexOf(args, name);
    return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
}

static void AppendBrokersMerge(StringBuilder sql, List<AssignmentFinder.Domain.Broker> brokers)
{
    sql.AppendLine("-- Brokers (matched by Name, the same natural key BrokerSeeder uses)");
    if (brokers.Count == 0)
    {
        sql.AppendLine("-- (none)");
        sql.AppendLine();
        return;
    }

    sql.AppendLine("SET IDENTITY_INSERT [Brokers] ON;");
    sql.AppendLine("MERGE INTO [Brokers] AS target");
    sql.AppendLine("USING (VALUES");
    sql.AppendLine(string.Join(",\n", brokers.Select(b => "    (" + string.Join(", ",
        SqlInt(b.Id),
        SqlString(b.Name),
        SqlString(b.WebsiteUrl),
        SqlString(b.AssignmentPortalUrl),
        SqlString(b.ConnectorKey),
        SqlString(b.SelectorConfigJson),
        SqlBool(b.IsEnabled),
        SqlString(b.LoginUsername),
        SqlString(b.LoginPasswordEncrypted),
        SqlString(b.LoginUrl)) + ")")));
    sql.AppendLine(") AS source (Id, Name, WebsiteUrl, AssignmentPortalUrl, ConnectorKey, SelectorConfigJson, IsEnabled, LoginUsername, LoginPasswordEncrypted, LoginUrl)");
    sql.AppendLine("ON target.Name = source.Name");
    sql.AppendLine("WHEN MATCHED THEN UPDATE SET");
    sql.AppendLine("    target.WebsiteUrl = source.WebsiteUrl,");
    sql.AppendLine("    target.AssignmentPortalUrl = source.AssignmentPortalUrl,");
    sql.AppendLine("    target.ConnectorKey = source.ConnectorKey,");
    sql.AppendLine("    target.SelectorConfigJson = source.SelectorConfigJson,");
    sql.AppendLine("    target.IsEnabled = source.IsEnabled,");
    sql.AppendLine("    target.LoginUsername = source.LoginUsername,");
    sql.AppendLine("    target.LoginPasswordEncrypted = source.LoginPasswordEncrypted,");
    sql.AppendLine("    target.LoginUrl = source.LoginUrl");
    sql.AppendLine("WHEN NOT MATCHED THEN INSERT (Id, Name, WebsiteUrl, AssignmentPortalUrl, ConnectorKey, SelectorConfigJson, IsEnabled, LoginUsername, LoginPasswordEncrypted, LoginUrl)");
    sql.AppendLine("VALUES (source.Id, source.Name, source.WebsiteUrl, source.AssignmentPortalUrl, source.ConnectorKey, source.SelectorConfigJson, source.IsEnabled, source.LoginUsername, source.LoginPasswordEncrypted, source.LoginUrl);");
    sql.AppendLine("SET IDENTITY_INSERT [Brokers] OFF;");
    sql.AppendLine();
}

static void AppendSearchCriteriaMerge(StringBuilder sql, List<AssignmentFinder.Domain.SearchCriterion> searchCriteria)
{
    sql.AppendLine("-- Saved searches (SearchCriteria), matched by Id - requires matching AspNetUsers(Id) rows to already exist");
    if (searchCriteria.Count == 0)
    {
        sql.AppendLine("-- (none)");
        sql.AppendLine();
        return;
    }

    sql.AppendLine("SET IDENTITY_INSERT [SearchCriteria] ON;");
    sql.AppendLine("MERGE INTO [SearchCriteria] AS target");
    sql.AppendLine("USING (VALUES");
    sql.AppendLine(string.Join(",\n", searchCriteria.Select(c => "    (" + string.Join(", ",
        SqlInt(c.Id),
        SqlString(c.UserId),
        SqlString(c.Name),
        SqlString(c.AreaKeywords),
        SqlString(c.RequirementKeywords),
        SqlInt(c.MinRequirementMatches),
        SqlBool(c.IsActive)) + ")")));
    sql.AppendLine(") AS source (Id, UserId, Name, AreaKeywords, RequirementKeywords, MinRequirementMatches, IsActive)");
    sql.AppendLine("ON target.Id = source.Id");
    sql.AppendLine("WHEN MATCHED THEN UPDATE SET");
    sql.AppendLine("    target.UserId = source.UserId,");
    sql.AppendLine("    target.Name = source.Name,");
    sql.AppendLine("    target.AreaKeywords = source.AreaKeywords,");
    sql.AppendLine("    target.RequirementKeywords = source.RequirementKeywords,");
    sql.AppendLine("    target.MinRequirementMatches = source.MinRequirementMatches,");
    sql.AppendLine("    target.IsActive = source.IsActive");
    sql.AppendLine("WHEN NOT MATCHED THEN INSERT (Id, UserId, Name, AreaKeywords, RequirementKeywords, MinRequirementMatches, IsActive)");
    sql.AppendLine("VALUES (source.Id, source.UserId, source.Name, source.AreaKeywords, source.RequirementKeywords, source.MinRequirementMatches, source.IsActive);");
    sql.AppendLine("SET IDENTITY_INSERT [SearchCriteria] OFF;");
    sql.AppendLine();
}

static void AppendDataProtectionKeysMerge(StringBuilder sql, List<DataProtectionKey> keys)
{
    sql.AppendLine("-- Data Protection keys (decrypt Broker.LoginPasswordEncrypted) - only portable because");
    sql.AppendLine("-- the app pins a fixed SetApplicationName(\"AssignmentFinder\"); see InfrastructureServiceCollectionExtensions.");
    if (keys.Count == 0)
    {
        sql.AppendLine("-- (none)");
        sql.AppendLine();
        return;
    }

    sql.AppendLine("SET IDENTITY_INSERT [DataProtectionKeys] ON;");
    sql.AppendLine("MERGE INTO [DataProtectionKeys] AS target");
    sql.AppendLine("USING (VALUES");
    sql.AppendLine(string.Join(",\n", keys.Select(k => "    (" + string.Join(", ",
        SqlInt(k.Id),
        SqlString(k.FriendlyName),
        SqlString(k.Xml)) + ")")));
    sql.AppendLine(") AS source (Id, FriendlyName, Xml)");
    sql.AppendLine("ON target.Id = source.Id");
    sql.AppendLine("WHEN MATCHED THEN UPDATE SET");
    sql.AppendLine("    target.FriendlyName = source.FriendlyName,");
    sql.AppendLine("    target.Xml = source.Xml");
    sql.AppendLine("WHEN NOT MATCHED THEN INSERT (Id, FriendlyName, Xml)");
    sql.AppendLine("VALUES (source.Id, source.FriendlyName, source.Xml);");
    sql.AppendLine("SET IDENTITY_INSERT [DataProtectionKeys] OFF;");
    sql.AppendLine();
}

static string SqlString(string? value) => value is null ? "NULL" : "N'" + value.Replace("'", "''") + "'";

static string SqlBool(bool value) => value ? "1" : "0";

static string SqlInt(int value) => value.ToString(CultureInfo.InvariantCulture);
